-- Canonical product catalog: one row per print size (product), with
-- Full/Border style variants and quantity + whole-package prices beneath each.
--
-- This replaces the earlier string-keyed product_variants / product_packages
-- (V23 / V24) with backend-generated BIGINT identities so every size is a
-- single product whose styles are chosen inside the product page.
--
-- print_sizes / product_meta / print_size_pricing_tiers are kept as the legacy
-- layer: historical order_items.size_id and the legacy per-print checkout path
-- still reference them, and duplicate rows are soft-retired (never deleted).

DROP TABLE IF EXISTS product_packages;
DROP TABLE IF EXISTS product_variants;

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(255) NOT NULL,
    display_name VARCHAR(255) NOT NULL,
    width DECIMAL(5,2),
    height DECIMAL(5,2),
    base_price DECIMAL(10,2),
    description TEXT,
    tag VARCHAR(50),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    CONSTRAINT uq_products_code UNIQUE (code)
);

CREATE TABLE product_variants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    style VARCHAR(16) NOT NULL,
    label VARCHAR(64) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    CONSTRAINT fk_product_variants_product FOREIGN KEY (product_id) REFERENCES products(id),
    CONSTRAINT uq_product_variants_style UNIQUE (product_id, style),
    CONSTRAINT chk_product_variants_style CHECK (style IN ('FULL', 'BORDER'))
);

CREATE TABLE product_packages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_id BIGINT NOT NULL,
    quantity INT NOT NULL,
    price DECIMAL(10,2) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'MYR',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    CONSTRAINT fk_product_packages_variant FOREIGN KEY (variant_id) REFERENCES product_variants(id),
    CONSTRAINT uq_product_packages_quantity UNIQUE (variant_id, quantity)
);

-- Legacy ids (e.g. ic-border, 2r-no-border) that now resolve to a style of a
-- canonical product, so old links and carts keep working after the merge.
CREATE TABLE product_aliases (
    legacy_code VARCHAR(255) PRIMARY KEY,
    product_id BIGINT NOT NULL,
    style VARCHAR(16),
    created_at TIMESTAMP,
    CONSTRAINT fk_product_aliases_product FOREIGN KEY (product_id) REFERENCES products(id)
);
